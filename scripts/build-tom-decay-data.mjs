import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataRoot = join(root, "public", "research", "tom-decay", "data");
const downloadRoot = join(root, "public", "research", "tom-decay", "downloads");
const outputPath = join(root, "lib", "research", "tom-decay", "generated", "frozen-sources.ts");

const datasets = [
  { id: "yahoo", directory: "yahoo" },
  { id: "french", directory: "french-matched" },
];

const sourceFiles = [
  { key: "publicationRegimeSummary", file: "publication_regime_summary.csv" },
  { key: "publicationAdjacentTests", file: "publication_adjacent_tests.csv" },
  { key: "breakTests", file: "break_tests.csv" },
  { key: "rollingPremium", file: "rolling_premium.csv" },
  { key: "calendarPairwiseTests", file: "calendar_pairwise_tests.csv" },
  { key: "researchReport", file: "research_report.json" },
];

const downloadFiles = ["reproduce_tom_decay.do", "qtomdecay_v0_3_1_statanow185.zip"];

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

function collect() {
  const sources = {};
  const hashes = {};
  const toolVersions = new Set();

  for (const { id, directory } of datasets) {
    const manifest = JSON.parse(readFileSync(join(dataRoot, directory, "manifest.json"), "utf8"));
    if (!manifest?.files) throw new Error(`manifest.json in ${directory} has no files map`);
    toolVersions.add(manifest.version);
    sources[id] = {};
    hashes[id] = {};

    for (const { key, file } of sourceFiles) {
      const bytes = readFileSync(join(dataRoot, directory, file));
      const digest = sha256(bytes);
      const declared = manifest.files[file]?.sha256;
      if (declared && declared !== digest) {
        throw new Error(
          `${directory}/${file} does not match its frozen manifest hash `
            + `(manifest ${declared}, file ${digest})`,
        );
      }
      sources[id][key] = bytes.toString("utf8");
      hashes[id][file] = digest;
    }
  }

  if (toolVersions.size !== 1) {
    throw new Error(`Datasets came from different tool versions: ${[...toolVersions].join(", ")}`);
  }

  const downloads = {};
  for (const file of downloadFiles) {
    downloads[file] = sha256(readFileSync(join(downloadRoot, file)));
  }

  return { sources, hashes, downloads, toolVersion: [...toolVersions][0] };
}

function render({ sources, hashes, downloads, toolVersion }) {
  const literal = (value) => JSON.stringify(value);
  const datasetBlock = (id) =>
    sourceFiles.map(({ key }) => `    ${key}: ${literal(sources[id][key])},`).join("\n");
  const hashBlock = (id) =>
    Object.entries(hashes[id]).map(([file, digest]) => `    ${literal(file)}: ${literal(digest)},`).join("\n");
  const downloadBlock = Object.entries(downloads)
    .map(([file, digest]) => `  ${literal(file)}: ${literal(digest)},`)
    .join("\n");

  return `// Generated by scripts/build-tom-decay-data.mjs. Do not edit by hand.
// Source of truth: public/research/tom-decay/data (frozen qtomdecay ${toolVersion} outputs).
import type { FrozenDatasetSources } from "../parse.ts";

export const frozenToolVersion = ${literal(toolVersion)};

export const frozenTomDecaySources: Record<"yahoo" | "french", FrozenDatasetSources> = {
  yahoo: {
${datasetBlock("yahoo")}
  },
  french: {
${datasetBlock("french")}
  },
};

export const frozenDataHashes: Record<"yahoo" | "french", Record<string, string>> = {
  yahoo: {
${hashBlock("yahoo")}
  },
  french: {
${hashBlock("french")}
  },
};

export const frozenDownloadHashes: Record<string, string> = {
${downloadBlock}
};
`;
}

const collected = collect();
const rendered = render(collected);

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== rendered) {
    console.error("TOM decay generated data is stale. Run: npm run build:tom-decay");
    process.exit(1);
  }
  console.log(
    `TOM decay data check passed: qtomdecay ${collected.toolVersion}, `
      + `${datasets.length} datasets, ${sourceFiles.length} frozen files each.`,
  );
} else {
  writeFileSync(outputPath, rendered);
  console.log(
    `Wrote ${outputPath.replace(`${root}/`, "")} (qtomdecay ${collected.toolVersion}, ${datasets.length} datasets).`,
  );
}
